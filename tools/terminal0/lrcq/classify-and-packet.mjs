// PPRCHK-198-02: enumerate the unresolved founder-fill placeholders MECHANICALLY, so they are visibly
// classified as stale on the face of the artifact rather than discoverable only by reading every value.
const placeholderLeaves = [];
(function scan(o, path) {
  if (Array.isArray(o)) { o.forEach((v, i) => scan(v, path + "[" + i + "]")); return; }
  if (o && typeof o === "object") { for (const [k, v] of Object.entries(o)) scan(v, path + "/" + k); return; }
  if (typeof o === "string" && /^<(founder|.*founder-fills|.*founder-mints)/.test(o)) placeholderLeaves.push({ field: path, placeholder: o });
})(gatePacket, "");
gatePacket.__unresolved_founder_placeholders = placeholderLeaves;
gatePacket.__unresolved_founder_placeholder_count = placeholderLeaves.length;
gatePacket.__placeholder_note = placeholderLeaves.length > 0
  ? "UNRESOLVED. These values are founder-fill placeholders, never real bindings. Preflight control PF-3 refuses any activation in which a '<founder' placeholder survives, so this packet can never be executed. It is STALE evidence, not run material."
  : "none";

// Fail closed rather than ever writing an unmarked stale packet again. Checked against the FIXED required
// contract above, never against the emitted table — a deletion from that table must be caught, not hidden.
const markerProblems = [];
for (const k of REQUIRED_MARKER_KEYS) {
  if (typeof gatePacket[k] !== "string" || gatePacket[k].trim() === "") markerProblems.push("MARKER_MISSING_OR_EMPTY: " + k);
}
if (gatePacket.__status !== REQUIRED_STATUS) markerProblems.push("MARKER_STATUS_WRONG: expected " + REQUIRED_STATUS + ", got " + String(gatePacket.__status));
if (gatePacket.__superseded_by !== REQUIRED_SUPERSEDED_BY) markerProblems.push("MARKER_SUPERSEDED_BY_WRONG: expected " + REQUIRED_SUPERSEDED_BY + ", got " + String(gatePacket.__superseded_by));
for (const rx of REQUIRED_REASON_FACTS) {
  if (!rx.test(String(gatePacket.__reason))) markerProblems.push("MARKER_REASON_INCOMPLETE: missing " + rx);
}
if (markerProblems.length) {
  console.error("REFUSED: staleness markers missing or altered in the generated packet:\n  " + markerProblems.join("\n  "));
  process.exit(3);
}
if (gatePacket.founder_signature !== null || gatePacket.confers_no_authority !== true) {
  console.error("REFUSED: the gate packet must remain unsigned and authority-free");
  process.exit(3);
}
const outDir = ".foundergate/evidence/lrcq-assurance-factory";
writeFileSync(P(outDir + "/UNSIGNED_GATE_PACKET.json"), JSON.stringify(gatePacket, null, 2) + "\n");
console.log("wrote UNSIGNED_GATE_PACKET.json  founder_signature:", gatePacket.founder_signature,
  " would_validate_when_signed:", would_validate_when_signed, " blockers:", blockerIds.length,
  " __status:", gatePacket.__status, " unresolved_placeholders:", placeholderLeaves.length);

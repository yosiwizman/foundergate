#!/usr/bin/env node
// FounderGate LRCQ — PROCEDURAL FINAL-HEAD CAPSULE generator (FG-PPRC-198, corrects PPRCHK-198-01).
//
// ---------------------------------------------------------------------------------------------------
// WHY THIS TOOL EXISTS: THE TWO ARTIFACTS ARE NOT THE SAME ARTIFACT
// ---------------------------------------------------------------------------------------------------
// PF-5 (run-five-hour.mjs) requires an activation's evidence_commit_sha/tree to equal the MECHANICALLY
// RESOLVED CURRENT HEAD/tree. That control is correct and is deliberately NOT weakened here.
//
// A commit cannot contain its own hash. So there are exactly two artifacts, at two different stages:
//
//   A. COMMITTED PACKAGE CANDIDATE — deterministic unsigned package material, committed in the repository.
//      It proves package-candidate bindings (authority candidate, provider identity, ceilings, exclusions)
//      and package-byte integrity. It CANNOT bind the final evidence head, because the evidence-only tail
//      commit that becomes that head does not exist yet when the candidate is written. It therefore never
//      claims binds_exact_final_head, and never claims PF-5 passes at a later evidence head.
//
//   B. PROCEDURAL FINAL-HEAD CAPSULE — generated by THIS TOOL, OUTSIDE the repository, only AFTER the
//      final evidence-only tail commit exists and its SHA/tree are mechanically known. It binds the exact
//      final HEAD and tree, so it reaches SIGNATURE-REQUIRED with zero binding defects. Because it is
//      never committed, it creates no self-reference and no recursive seal.
//
// The prior wave conflated the two: it froze a capsule at the package candidate 58b3620, then committed
// evidence claiming SIGNATURE-REQUIRED / binds_exact_final_head:true — in the very commit (46f1f0d) that
// advanced HEAD and falsified those claims. At 46f1f0d the real results were BINDING-DEFECT and
// CAPSULE-VERIFIER INVALID. PF-5 fired correctly and failed CLOSED; the defect was the false evidence.
//
// ---------------------------------------------------------------------------------------------------
// AUTHORITY-BEARING PROPERTIES
// ---------------------------------------------------------------------------------------------------
//   * The final HEAD and tree are EXPLICIT REQUIRED INPUTS, never inferred. This tool then independently
//     resolves HEAD/HEAD^{tree} from git and REFUSES unless the declared values match exactly. Declaring
//     the wrong head, or the right head with the wrong tree, is a refusal — not a silently-rebound capsule.
//   * It writes NOTHING into the repository. The output root must resolve outside it (generate-capsule.mjs
//     enforces that independently, including through symlinked ancestors).
//   * It never signs, enrolls a key, issues, consumes, merges, pushes, deploys, or invokes a provider or
//     model productively. Provider contact is limited to the digest re-hash the production verifier does.
//   * It reuses the AUTHORITATIVE production components rather than duplicating them:
//       generateCapsule()  (generate-capsule.mjs)  — the deterministic capsule generator
//       verifyCapsule()    (capsule-verifier.mjs)  — the production capsule verifier
//       run-five-hour.mjs --final-template-preflight — the production preflight, PF-5 included
//   * The receipt goes to STDOUT. It is deliberately NOT written into the repository: a receipt asserting
//     the final head, committed at that head, would be exactly the recursive self-seal this design avoids.
//
// Usage:
//   final-head-capsule.mjs --final-head <40-hex> --final-tree <40-hex> --evaluated-sha <40-hex> \
//                          --out-root <absolute dir OUTSIDE the repository> --capsule-name <name> \
//                          --pr <number> [--allow-dirty-check-skip=no]
//
// Every input is required. There are no defaults, because a default would let this tool bind something
// other than what the operator declared.

import { readFileSync, existsSync, mkdirSync } from "node:fs";
import { execFileSync } from "node:child_process";
import { fileURLToPath } from "node:url";
import { dirname, resolve, isAbsolute, join } from "node:path";
import { fixedGit } from "../../../src/v8b/lrcq/assurance/fixed-executables.mjs";
import { generateCapsule } from "./generate-capsule.mjs";
import { verifyCapsule } from "./capsule-verifier.mjs";

const SELF = fileURLToPath(import.meta.url);
const REPO = resolve(dirname(SELF), "../../..");
const git = (...a) => fixedGit(["-C", REPO, ...a]);
const HEX40 = /^[0-9a-f]{40}$/;

export function main(argv) {
  const arg = (n) => { const i = argv.indexOf(n); return i >= 0 ? argv[i + 1] : undefined; };
  const finalHead = arg("--final-head");
  const finalTree = arg("--final-tree");
  const evaluatedSha = arg("--evaluated-sha");
  const outRoot = arg("--out-root");
  const capsuleName = arg("--capsule-name");
  const prRaw = arg("--pr");

  const refuse = (code, detail) => {
    console.error(JSON.stringify({ result: "REFUSED", code, detail, capsule_generated: false, provider_spawns: 0 }, null, 2));
    return 2;
  };

  // ---- 1. every input is explicit -----------------------------------------------------------------
  if (!finalHead || !HEX40.test(finalHead)) return refuse("FINAL_HEAD_REQUIRED", "--final-head <40-hex> is required");
  if (!finalTree || !HEX40.test(finalTree)) return refuse("FINAL_TREE_REQUIRED", "--final-tree <40-hex> is required");
  if (!evaluatedSha || !HEX40.test(evaluatedSha)) return refuse("EVALUATED_SHA_REQUIRED", "--evaluated-sha <40-hex> is required");
  if (!outRoot || !isAbsolute(outRoot)) return refuse("OUT_ROOT_REQUIRED", "--out-root <absolute dir outside the repository> is required");
  if (!capsuleName || !/^[A-Za-z0-9._-]+$/.test(capsuleName)) return refuse("CAPSULE_NAME_INVALID", "--capsule-name must be a plain name");
  const prNumber = Number(prRaw);
  if (!Number.isInteger(prNumber) || prNumber <= 0) return refuse("PR_REQUIRED", "--pr <number> is required");

  // ---- 2. the declared final head/tree must be the REAL current head/tree -------------------------
  // This is the check that makes the whole two-stage design safe. The capsule binds whatever HEAD is,
  // so a declared head that is not HEAD would silently produce a capsule bound to something else.
  let realHead, realTree, branch;
  try { realHead = git("rev-parse", "HEAD"); realTree = git("rev-parse", "HEAD^{tree}"); branch = git("rev-parse", "--abbrev-ref", "HEAD"); }
  catch (e) { return refuse("GIT_UNAVAILABLE", String(e && e.message)); }
  if (finalHead !== realHead) return refuse("DECLARED_FINAL_HEAD_IS_NOT_CURRENT_HEAD", "declared " + finalHead + " != resolved " + realHead);
  if (finalTree !== realTree) return refuse("DECLARED_FINAL_TREE_IS_NOT_CURRENT_TREE", "declared " + finalTree + " != resolved " + realTree);

  // ---- 3. the tree must be clean, or the capsule would bind bytes the commit does not contain -----
  let dirty = "";
  try { dirty = git("status", "--porcelain"); } catch { /* handled below */ }
  if (dirty && dirty.trim() !== "") return refuse("WORKTREE_NOT_CLEAN", "the capsule would bind uncommitted bytes:\n" + dirty);

  // ---- 4. the evaluated ancestor must be a real, distinct ancestor --------------------------------
  if (evaluatedSha === finalHead) return refuse("EVALUATED_SHA_EQUALS_FINAL_HEAD", "the reviewed production ancestor and the evidence commit must be distinct (non-recursive two-SHA seal)");
  let isAnc = false;
  try { git("merge-base", "--is-ancestor", evaluatedSha, finalHead); isAnc = true; } catch { isAnc = false; }
  if (!isAnc) return refuse("EVALUATED_SHA_NOT_AN_ANCESTOR", evaluatedSha + " is not an ancestor of " + finalHead);

  // ---- 5. out-root must exist and resolve outside the repository ----------------------------------
  // generate-capsule.mjs re-checks this independently (including symlinked ancestors); this is a clear
  // early refusal with a useful message.
  try { mkdirSync(outRoot, { recursive: true }); } catch (e) { return refuse("OUT_ROOT_UNUSABLE", String(e && e.message)); }
  if (resolve(outRoot) === REPO || resolve(outRoot).startsWith(REPO + "/")) return refuse("OUT_ROOT_INSIDE_REPOSITORY", outRoot);
  if (existsSync(join(outRoot, capsuleName))) return refuse("CAPSULE_DESTINATION_EXISTS", join(outRoot, capsuleName));

  // ---- 6. live PR metadata (the capsule binds the PR body digest) ---------------------------------
  const gh = (n) => {
    try {
      const t = execFileSync("gh", ["pr", "view", String(n), "--json", "title", "-q", ".title"], { encoding: "utf8" }).replace(/\n$/, "");
      const b = execFileSync("gh", ["pr", "view", String(n), "--json", "body", "-q", ".body"], { encoding: "utf8" });
      return { title: t, body: b };
    } catch { return null; }
  };
  const ghHeadOf = (n) => {
    try { return execFileSync("gh", ["pr", "view", String(n), "--json", "headRefOid", "-q", ".headRefOid"], { encoding: "utf8" }).trim(); } catch { return null; }
  };
  const md = gh(prNumber);
  if (!md) return refuse("PR_METADATA_UNAVAILABLE", "live PR #" + prNumber + " title/body could not be read");
  const ghHead = ghHeadOf(prNumber);
  if (ghHead && ghHead !== finalHead) return refuse("GITHUB_PR_HEAD_IS_NOT_THE_DECLARED_FINAL_HEAD", "GitHub " + ghHead + " != declared " + finalHead);

  let protectedMain = null;
  try { protectedMain = git("rev-parse", "refs/remotes/origin/main"); } catch { /* */ }
  if (!protectedMain) return refuse("PROTECTED_MAIN_UNRESOLVED", "refs/remotes/origin/main did not resolve");

  // ---- 7. generate the capsule OUTSIDE the repository ---------------------------------------------
  const gen = generateCapsule({
    repoRoot: REPO, evaluatedSha, branch, prNumber,
    prTitle: md.title, prLiveBody: md.body, prStoredBody: md.body,
    protectedMainBaseline: protectedMain, githubHead: finalHead,
    approvedOutputRoot: outRoot, capsuleName,
    gh: () => finalHead,
  });
  if (!gen.ok) {
    console.error(JSON.stringify({ result: "CAPSULE_GENERATION_FAILED", stage: gen.stage, errors: gen.errors, provider_spawns: 0 }, null, 2));
    return 3;
  }
  const capsuleDir = gen.outDir;

  // ---- 8. verify the capsule with the PRODUCTION verifier -----------------------------------------
  const ver = verifyCapsule({ repo: REPO, capsuleDir, prNumber, githubMetadataProvider: gh });

  // ---- 9. run the PRODUCTION final-template preflight (PF-5 included, unweakened) -----------------
  let preflight = null, preflightRaw = "";
  try {
    preflightRaw = execFileSync(process.execPath, [
      join(REPO, "tools/terminal0/lrcq/run-five-hour.mjs"),
      "--final-template-preflight", join(capsuleDir, "FINAL_UNSIGNED_ACTIVATION_TEMPLATE.json"),
    ], { encoding: "utf8", cwd: REPO });
  } catch (e) { preflightRaw = (e.stdout || "") + (e.stderr || ""); }
  try { preflight = JSON.parse(preflightRaw.slice(preflightRaw.indexOf("{"), preflightRaw.lastIndexOf("}") + 1)); } catch { preflight = null; }

  const systemState = JSON.parse(readFileSync(join(capsuleDir, "SYSTEM_STATE.json"), "utf8"));
  const finalTpl = JSON.parse(readFileSync(join(capsuleDir, "FINAL_UNSIGNED_ACTIVATION_TEMPLATE.json"), "utf8"));

  const bindsExactFinalHead =
    systemState.frozen_head === finalHead && systemState.frozen_tree === finalTree
    && finalTpl.evidence_commit_sha === finalHead && finalTpl.evidence_commit_tree === finalTree;

  const preflightOk = !!preflight && preflight.result === "SIGNATURE-REQUIRED"
    && Array.isArray(preflight.binding_defects) && preflight.binding_defects.length === 0
    && preflight.invocations && preflight.invocations.providerSpawn === 0;

  const receipt = {
    schema: "lrcq-procedural-final-head-capsule-receipt-1",
    wave: "FG-PPRC-198 (PPRCHK-198-01 correction)",
    stage: "B — PROCEDURAL FINAL-HEAD CAPSULE (generated outside Git; NEVER committed)",
    not_committed: true,
    why_not_committed: "A receipt asserting the final head, committed at that head, would be a recursive self-seal. This receipt lives outside the repository; the capsule is bound by digest in the evidence tail instead.",
    declared_inputs: { final_head: finalHead, final_tree: finalTree, evaluated_sha: evaluatedSha, out_root: outRoot, capsule_name: capsuleName, pr: prNumber },
    mechanically_resolved: { head: realHead, tree: realTree, branch, protected_main: protectedMain, github_pr_head: ghHead },
    declared_equals_resolved: true,
    worktree_clean: true,
    capsule_dir: capsuleDir,
    capsule_is_outside_the_repository: true,
    capsule_members: gen.files,
    system_state: { frozen_head: systemState.frozen_head, frozen_tree: systemState.frozen_tree, evaluated_sha: systemState.evaluated_sha, evaluated_tree: systemState.evaluated_tree, founder_signature: systemState.founder_signature },
    final_template: { schema: finalTpl.schema_version, evidence_commit_sha: finalTpl.evidence_commit_sha, evidence_commit_tree: finalTpl.evidence_commit_tree, reviewed_runtime_sha: finalTpl.reviewed_runtime_sha, reviewed_runtime_tree: finalTpl.reviewed_runtime_tree, founder_signature: finalTpl.founder_signature, unsigned: finalTpl.unsigned },
    binds_exact_final_head: bindsExactFinalHead,
    capsule_verifier: { result: ver.valid ? "VALID" : "INVALID", checks_passed: (ver.checks || []).filter((c) => c.pass).length, checks_failed: (ver.problems || []).length, problems: ver.problems || [] },
    final_preflight: preflight ? { result: preflight.result, founder_gate: preflight.founder_gate, binding_defects: preflight.binding_defects, invocations: preflight.invocations, zero_invocation: preflight.zero_invocation } : { result: "UNPARSEABLE", raw_tail: preflightRaw.slice(-400) },
    provider_spawns: preflight && preflight.invocations ? preflight.invocations.providerSpawn : null,
    signed: false, activated: false, key_enrolled: false, run_started: false,
    overall: bindsExactFinalHead && ver.valid && preflightOk ? "FINAL_HEAD_CAPSULE_VERIFIED" : "FINAL_HEAD_CAPSULE_NOT_VERIFIED",
  };
  console.log(JSON.stringify(receipt, null, 2));
  return receipt.overall === "FINAL_HEAD_CAPSULE_VERIFIED" ? 0 : 4;
}

if (SELF === resolve(process.argv[1] || "")) process.exit(main(process.argv.slice(2)));

// FounderGate Local App Factory — engine. Instantiates an archetype into its own folder, runs its real
// app-specific selftest, and binds the outcome into a manifest. DONE requires files on disk; PASS requires
// the app's own tests to actually pass; preview_url is the generated artifact path (never hardcoded).
import { ARCHETYPES } from './archetypes.mjs';
import { requestHash } from '../idea_builder/template-registry.mjs';
import { execFileSync } from 'node:child_process';
import { writeFileSync, mkdirSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const REPO = join(dirname(fileURLToPath(import.meta.url)), '..', '..');

// Deterministic seeded selection (no Math.random): seed from a timestamp string; LCG shuffle a copy of ids.
export function selectArchetypes(seedStr, ids, n) {
  let seed = 0; for (const ch of String(seedStr)) seed = (seed * 31 + ch.charCodeAt(0)) >>> 0;
  const rnd = () => { seed = (seed * 1664525 + 1013904223) >>> 0; return seed / 0xffffffff; };
  const arr = ids.slice();
  for (let i = arr.length - 1; i > 0; i--) { const j = Math.floor(rnd() * (i + 1)); [arr[i], arr[j]] = [arr[j], arr[i]]; }
  return arr.slice(0, n);
}

function runSelftest(testPathRel) {
  try {
    const out = execFileSync('node', [join(REPO, testPathRel)], { cwd: REPO, timeout: 30000, encoding: 'utf8', env: { PATH: process.env.PATH } });
    const m = out.match(/ALL GREEN:\s*(\d+)\/(\d+)/);
    if (m) return { ran: true, ok: true, result: `PASS ${m[1]}/${m[2]}`, passed: +m[1], total: +m[2] };
    return { ran: true, ok: false, result: 'RAN_NO_GREEN', raw: out.slice(0, 200) };
  } catch (e) { return { ran: true, ok: false, result: 'FAIL', raw: String(e.stdout || e.message).slice(0, 200) }; }
}

// Generate one app from an archetype and run its tests. Returns the bound manifest.
// opts.runsDir selects the output subfolder (default 'factory_runs'; Round 2 uses 'factory_round2').
export function generateAndTest(archetypeId, opts = {}) {
  const a = ARCHETYPES[archetypeId];
  if (!a) throw new Error('unknown archetype ' + archetypeId);
  const runsDir = opts.runsDir || 'factory_runs';
  const request_text = a.request_text;
  const request_hash = requestHash(request_text);
  const request_id = 'req_' + request_hash;
  const relDir = `tests/generated_apps/${runsDir}/${request_id}`;
  const absDir = join(REPO, relDir);
  mkdirSync(join(absDir, 'tests'), { recursive: true });

  const files = {
    'core.mjs': a.core(),
    'index.html': a.html(),
    ['tests/' + a.test_name]: a.test(),
    'LIMITATIONS.md': `# ${a.title} — Limitations (local synthetic)\n- In-memory only; no storage, network, accounts, backend, or deploy.\n- Synthetic/local demo generated by the FounderGate app factory from the "${a.id}" archetype.\n- NOT production/secure/SaaS/customer-ready/commercial. Decision never "ship".\n- Bound to request ${request_id} (hash ${request_hash}); preview + tests belong to THIS app.\n`,
    'package.json': JSON.stringify({ name: `foundergate-factory-${a.id}`, version: '0.0.1', private: true, type: 'module', description: `Local synthetic ${a.title} generated by the FounderGate app factory.` }, null, 2) + '\n',
  };
  const generated_files = [];
  for (const [rel, content] of Object.entries(files)) { writeFileSync(join(absDir, rel), content); generated_files.push(rel); }

  const testRel = `${relDir}/tests/${a.test_name}`;
  const t = runSelftest(testRel);
  const preview_url = `../../tests/generated_apps/${runsDir}/${request_id}/index.html`;

  const manifest = {
    manifest_kind: 'FACTORY_APP_MANIFEST',
    request_id, request_text, request_hash,
    selected_template_id: a.id,
    app_spec: { title: a.title, archetype: a.id, actions: 'input + state-change + reset/delete/clear', local_only: true, synthetic_only: true },
    generated_app_path: relDir,
    generated_files,
    test_plan: `${relDir}/tests/${a.test_name}`,
    test_results: { tests_run: t.ran, result: t.ok ? t.result : `HOLD (${t.result})`, passed: t.passed || 0, total: t.total || 0 },
    preview_url,
    evidence_manifest: `${relDir}/manifest.json`,
    builder_identity: 'FounderGate local app factory',
    checker_verdict: 'PENDING_INDEPENDENT_CHECKER',
    terminal_advisor_verdict: 'PENDING_INDEPENDENT_TERMINAL_ADVISOR',
    // DONE requires files on disk (they exist); PASS requires tests to have passed.
    final_status: (generated_files.length && t.ok) ? 'BUILT_AND_PASSED' : 'HOLD_TESTS_FAILED',
    ...(opts.extra || {}),   // e.g. { provider_id, run_id, mode } merged in by the provider harness
  };
  writeFileSync(join(absDir, 'manifest.json'), JSON.stringify(manifest, null, 2));
  return { ...manifest, absDir, relDir };
}
